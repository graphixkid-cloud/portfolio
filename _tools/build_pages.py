#!/usr/bin/env python3
"""Build the case-study pages and the home-page case cards.

Source of truth for each case study: _tools/cases/<slug>.html (the full <article>).
This script:
  1. writes work/<slug>/index.html for each case study (own title, description,
     social preview, structured data, previous/next links),
  2. regenerates the case cards on index.html between the cases:start/cases:end markers,
  3. rewrites sitemap.xml,
  4. regenerates the Portfolio Assistant's knowledge (_worker/src/knowledge.js).

Shared head, styles, header, contact section, footer and scripts are copied from
index.html, so a style or header change there carries over the next time this runs.

Run from the repository root:  python3 _tools/build_pages.py
"""
import html, json, re, sys
from datetime import date
from pathlib import Path

ROOT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent
SITE = "https://rickhollandsworth.com"
TODAY = date.today().isoformat()

CASES = [
    dict(slug="verizon-family",
         title="Verizon Family app redesign · UX case study",
         description="How Rick Hollandsworth led a 30-person design organization to consolidate five Verizon family apps into one, turning NPS around by 20 points in a year."),
    dict(slug="ebs",
         title="EBS BrokerTec FX trading platform · UX case study",
         description="One HTML5 trading screen for EBS Market spot and EBS Direct FX Forwards, validated with traders in London and New York: $41B daily volume, 10,000 institutional users."),
    dict(slug="gizmo-watch",
         title="Verizon Gizmo Watch kids' smartwatch · UX case study",
         description="Designing a smartwatch worn by a six-year-old and trusted by a parent: on-watch UX, the GizmoHub companion app and award-winning child-safety design."),
    dict(slug="care-smart",
         title="Verizon Care Smart senior smartwatch · UX case study",
         description="A smartwatch and family app that give older adults independence and their families reassurance: radically simple watch UX, an intentional Get Help slider and fall detection."),
    dict(slug="finfront",
         title="FinFront UI SDK fintech design system · Case study",
         description="A 75-component fintech design system across five financial verticals, with live documentation and working prototypes, built Claude-first by Rick Hollandsworth."),
]

PDFS = {  # path: lastmod
    "assets/pdf/rick-hollandsworth-resume.pdf": "2026-10-18",
    "assets/pdf/ebs-case-study.pdf": "2026-10-01",
    "assets/pdf/finfront-overview.pdf": "2026-10-01",
    "assets/pdf/finfront-design-library-case-study.pdf": "2026-10-02",
    "assets/pdf/finfront-ai-assistant-case-study.pdf": "2026-10-16",
}

# Portfolio Assistant (assets/js/ask.js). ASK_ENDPOINT is the deployed Worker's /chat URL.
# While ASK_PREVIEW is True the chat only appears for visitors who open a page with ?ask=1 (and ?ask=0 hides it again).
ASK_ENDPOINT = "https://portfolio-assistant.graphixkid.workers.dev/chat"
ASK_PREVIEW = True
ASK_START = "<!-- ask:start (generated by _tools/build_pages.py) -->"
ASK_END = "<!-- ask:end -->"


def ask_tag(prefix, page):
    preview = " data-preview" if ASK_PREVIEW else ""
    return f'<script src="{prefix}assets/js/ask.js" defer data-endpoint="{ASK_ENDPOINT}" data-page="{page}"{preview}></script>'


START = "    <!-- cases:start (generated by _tools/build_pages.py; edit _tools/cases/*.html instead) -->\n"
END = "    <!-- cases:end -->\n"


def between(s, a, b, include=True):
    i = s.index(a); j = s.index(b, i) + (len(b) if include else 0)
    return s[i:j]


def first(pattern, s, flags=re.S):
    m = re.search(pattern, s, flags)
    if not m:
        raise SystemExit(f"pattern not found: {pattern[:60]}")
    return m.group(1)


def relink(fragment, prefix="../../"):
    """Make asset links work from /work/<slug>/ and point in-page anchors at the home page."""
    fragment = re.sub(r'((?:src|href|poster)=")assets/', r'\1' + prefix + 'assets/', fragment)
    fragment = re.sub(r'href="#(work|about|recommendations|contact|top)"', r'href="' + prefix + r'#\1"', fragment)
    return fragment


def main():
    index_path = ROOT / "index.html"
    home = index_path.read_text(encoding="utf-8")

    style = between(home, "<style>", "</style>")
    fonts = between(home, '<link rel="preconnect" href="https://fonts.googleapis.com">', "display=swap\">")
    header = between(home, '<header class="site-header">', "</header>")
    contact = between(home, '<section class="block contact" id="contact"', "</section>")
    footer = between(home, '<footer class="site-footer">', "</footer>")
    scripts = between(home, "<script>\n(function(){", "<!-- /analytics -->")
    person_name = "Rick Hollandsworth"

    articles = {c["slug"]: (ROOT / "_tools" / "cases" / f"{c['slug']}.html").read_text(encoding="utf-8") for c in CASES}

    # ---------- case pages ----------
    for n, c in enumerate(CASES):
        slug = c["slug"]; art = articles[slug]
        url = f"{SITE}/work/{slug}/"
        h3 = first(r"<h3>(.*?)</h3>", art)
        hero_img = re.search(r'class="case-hero media">\s*<figure>.*?(?:src|poster)="assets/img/([^"]+)"', art, re.S).group(1)
        og = f"{SITE}/assets/img/og-{slug}.jpg"
        page_art = art.replace("<h3>", '<h1 class="case-title">').replace("</h3>", "</h1>")
        page_art = page_art.replace("<h4>", '<h2 class="kicker">').replace("</h4>", "</h2>")
        page_art = relink(page_art)
        prev_c = CASES[n - 1] if n > 0 else None
        next_c = CASES[n + 1] if n + 1 < len(CASES) else None

        def case_name(cc):
            return html.unescape(first(r"<h3>(.*?)</h3>", articles[cc["slug"]]))

        nav = ['<nav class="case-nav" aria-label="More case studies">']
        nav.append(f'  <a class="case-nav-prev" href="../{prev_c["slug"]}/"><span>Previous case study</span><b>{html.escape(case_name(prev_c))}</b></a>' if prev_c else '  <a class="case-nav-prev" href="../../#work"><span>Back to</span><b>All work</b></a>')
        nav.append(f'  <a class="case-nav-next" href="../{next_c["slug"]}/"><span>Next case study</span><b>{html.escape(case_name(next_c))}</b></a>' if next_c else '  <a class="case-nav-next" href="../../#work"><span>Back to</span><b>All work</b></a>')
        nav.append("</nav>")

        ld = {
            "@context": "https://schema.org",
            "@graph": [
                {"@type": "Article", "@id": url + "#case-study", "headline": c["title"], "name": html.unescape(h3),
                 "description": c["description"], "url": url, "image": og, "inLanguage": "en",
                 "author": {"@type": "Person", "@id": f"{SITE}/#rick", "name": person_name, "url": f"{SITE}/"},
                 "isPartOf": {"@type": "WebSite", "name": person_name, "url": f"{SITE}/"}},
                {"@type": "BreadcrumbList", "itemListElement": [
                    {"@type": "ListItem", "position": 1, "name": "Work", "item": f"{SITE}/#work"},
                    {"@type": "ListItem", "position": 2, "name": html.unescape(h3), "item": url}]},
            ],
        }
        full_title = f"{c['title']} · Rick Hollandsworth"
        e = html.escape
        head = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>{e(full_title)}</title>
<meta name="description" content="{e(c['description'])}">
<meta name="author" content="{person_name}">
<link rel="canonical" href="{url}">
<meta property="og:type" content="article">
<meta property="og:url" content="{url}">
<meta property="og:title" content="{e(full_title)}">
<meta property="og:description" content="{e(c['description'])}">
<meta property="og:image" content="{og}">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:site_name" content="{person_name}">
<meta property="og:locale" content="en_US">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="{e(full_title)}">
<meta name="twitter:description" content="{e(c['description'])}">
<meta name="twitter:image" content="{og}">
<script type="application/ld+json">
{json.dumps(ld, ensure_ascii=False, indent=1)}
</script>
<link rel="icon" type="image/png" href="../../assets/img/favicon.png">
<link rel="apple-touch-icon" href="../../assets/img/apple-touch-icon.png">
{fonts}
{style}
<link rel="stylesheet" href="../../assets/css/ask.css">
</head>
<body>
<a class="skip" href="#case">Skip to case study</a>

{relink(header).replace('href="../../#top"', 'href="../../"')}

<main id="top">
<section class="block case-page" aria-label="{e(html.unescape(h3))} case study">
  <div class="wrap" id="case">
    <p class="crumbs"><a href="../../#work">← All work</a></p>
{page_art.rstrip()}
    {chr(10).join(nav)}
  </div>
</section>

{relink(contact)}
</main>

{footer}

{scripts}
{ask_tag("../../", slug)}
</body>
</html>
"""
        out = ROOT / "work" / slug / "index.html"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(head, encoding="utf-8")

    # ---------- home cards ----------
    cards = []
    for c in CASES:
        slug = c["slug"]; art = articles[slug]
        num = first(r'(<span class="case-num">.*?</span>)', art)
        h3 = first(r"<h3>(.*?)</h3>", art)
        thesis = first(r'(<p class="thesis">.*?</p>)', art)
        stats = first(r'(<div class="case-stats">.*?</div>\s*</div>)', art)
        hero = first(r'<div class="case-hero media">\s*(<figure>.*?</figure>)', art)
        link = f'work/{slug}/'
        cards.append(f"""    <article class="case case-card" id="{slug}">
      <div class="case-intro">
        <div class="case-summary">
          {num}
          <h3><a href="{link}">{h3}</a></h3>
          {thesis}
          {stats.strip()}
          <a class="btn btn-primary" href="{link}" data-goatcounter-click="open-case-{slug}" data-goatcounter-title="Open case study: {html.escape(html.unescape(h3))}">Read the case study <span aria-hidden="true">→</span></a>
        </div>
        <div class="case-hero media"><a href="{link}" tabindex="-1" aria-hidden="true">{hero}</a></div>
      </div>
    </article>
""")
    i = home.index(START) + len(START); j = home.index(END)
    home = home[:i] + "\n".join(cards) + home[j:]

    # ---------- assistant tags on the home page ----------
    css = '<link rel="stylesheet" href="assets/css/ask.css">'
    if css not in home:
        home = home.replace("</head>", css + "\n</head>", 1)
    if ASK_START not in home:
        home = home.replace("<!-- /analytics -->", "<!-- /analytics -->\n" + ASK_START + "\n" + ASK_END, 1)
    i = home.index(ASK_START) + len(ASK_START); j = home.index(ASK_END)
    home = home[:i] + "\n" + ask_tag("", "home") + "\n" + home[j:]
    index_path.write_text(home, encoding="utf-8")

    # ---------- sitemap ----------
    urls = [(f"{SITE}/", TODAY)] + [(f"{SITE}/work/{c['slug']}/", TODAY) for c in CASES] + [(f"{SITE}/{p}", d) for p, d in PDFS.items()]
    sm = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for u, d in urls:
        sm += ["  <url>", f"    <loc>{u}</loc>", f"    <lastmod>{d}</lastmod>", "  </url>"]
    sm.append("</urlset>")
    (ROOT / "sitemap.xml").write_text("\n".join(sm) + "\n", encoding="utf-8")
    print("built", [c["slug"] for c in CASES])

    # ---------- assistant knowledge ----------
    from knowledge import write_knowledge
    print("knowledge", write_knowledge(ROOT))


if __name__ == "__main__":
    main()
